 cases.push(("backticks-varied",e,Box::new(|n|{let mut s=String::new(); for i in 1..(n as f64).sqrt() as usize {s.push_str(&"`".repeat(i)); s.push(' ');} s})));
 cases.push(("html-open",e,Box::new(|n|"a <a ".repeat(n))));
 cases.push(("html-comment",e,Box::new(|n|"a <!-- ".repeat(n))));
 cases.push(("html-cdata",e,Box::new(|n|"a <![CDATA[ ".repeat(n))));
