use pulldown_cmark::*; use std::time::Instant;
fn t(name:&str, op:Options, gen:&dyn Fn(usize)->String, ns:&[usize]){ let mut prev=0.0; for &n in ns { let s=gen(n); let st=Instant::now(); let c=Parser::new_ext(&s,op).count(); let d=st.elapsed().as_secs_f64(); println!("{name:<28} n={n:<8} bytes={:<9} events={c:<8} {:.3}s ratio={:.1}",s.len(),d,if prev>0.0{d/prev}else{0.0}); prev=d; if d>25.0{break;} } }
